export interface CountryInfo {
  id: string; // ISO 3166-1 numeric, matches topojson feature id
  name: string; // English name (from map data)
  nameKR: string; // Korean display name
}

export function getCountryLabel(name: string): string {
  return COUNTRIES.find((c) => c.name === name)?.nameKR ?? name;
}

export function getCountryById(id: string): CountryInfo | undefined {
  return COUNTRIES.find((c) => c.id === id);
}

